  <script>
$(document).ready(function() {

    function getFilters(className) {
        let values = [];
        $(className + ':checked').each(function() {
            values.push($(this).val());
        });
        return values;
    }

    function loadShopProducts() {

        let colors = getFilters('.filter-color');
        let sizes = getFilters('.filter-size');
        let prices = getFilters('.filter-price');

        $.ajax({
            url: '../api/products/get_products.php',
            type: 'GET',
            data: {
                color: colors,
                size: sizes,
                price: prices
            },
            dataType: 'json',
            success: function(response) {

                if(response.length === 0) {
                    $('#dynamic-products').html('<div class="col-12 text-center">No products found.</div>');
                    return;
                }

                let html = '';

                response.forEach(product => {
                    let img = product.image_url ? product.image_url : '../assets/img/default.jpg';

                    html += `
                    <div class="col-lg-4 col-md-6 col-sm-12 pb-1">
                        <div class="card product-item border-0 mb-4 shadow-sm">
                            <div class="card-header product-img">
                                <img class="img-fluid w-100" src="${img}">
                            </div>
                            <div class="card-body text-center">
                                <h6>${product.name}</h6>
                                <h6>$${product.price}</h6>
                            </div>
                        </div>
                    </div>`;
                });

                $('#dynamic-products').html(html);
            }
        });
    }

    // 🔥 Trigger filter change
    $(document).on('change', '.filter-color, .filter-size, .filter-price', function() {
        loadShopProducts();
    });

    loadShopProducts();
});
</script> 

